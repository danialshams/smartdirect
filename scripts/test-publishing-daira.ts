import assert from "node:assert/strict";
import { readFileSync, existsSync } from "node:fs";
const src = (p: string) => readFileSync(p, "utf8");
const root = "components/dashboard/publishing/";
const wizard = src(root+"PublishingDashboardV2.tsx");
const queue = src(root+"PublishingQueue.tsx");
const progress = src(root+"PublishingWizardProgress.tsx");
const skeleton = src(root+"PublishingPageSkeleton.tsx");
const edit = src(root+"PublishingJobEditor.tsx");
const tags = src(root+"PublishingWithTags.tsx");
const workflow = src("app/dashboard/publishing/page.tsx");
assert.match(wizard, /activeTab\s*===\s*"queue"/, "Publishing must have a separate queue tab");
assert.match(wizard, /<PublishingQueue/, "Publishing must render the queue");
assert.match(wizard, /<PublishingWizardProgress/, "Publishing must render four-stage progress");
assert.ok(wizard.includes("چه محتوایی می‌خواهید منتشر کنید؟"), "Compact content selector is missing");
assert.ok(wizard.includes("تگ کردن کاربران") && wizard.includes("showTags &&"), "Optional tags accordion is missing");
assert.ok(wizard.includes("ادامه به پاسخ خودکار"), "Details must advance to automation");
assert.ok(wizard.includes('name="publishing-mode"') && wizard.includes("زمان‌بندی انتشار"), "Explicit publishing mode radio choice required");
assert.ok(wizard.includes("onClick={()=>void createJob(publishNow)}"), "Both publishing modes must use the existing engine");
assert.ok(wizard.includes('const selectedScheduleDate = !publishNow ? stage6Date : scheduledDate;'), "Story scheduling must honor the chosen date");
assert.ok(wizard.includes('const selectedHour = !publishNow ? stage6Hour : hour;'), "Story scheduling must honor the chosen hour");
assert.ok(wizard.includes('const selectedMinute = !publishNow ? stage6Minute : minute;'), "Story scheduling must honor the chosen minute");
assert.ok(!wizard.includes("const scheduledJobs = jobs"), "Queue must not be embedded in content type selector");
assert.ok(wizard.includes('import dynamic from "next/dynamic"'), "Heavy story editor must load on demand");
assert.ok(wizard.includes('automationEnabled && type === "STORY"'), "Story resources should not load before enabling automation");
assert.ok(queue.includes("onRetry") && queue.includes("onCancel") && queue.includes("در انتظار"), "Queue needs basic recovery and cancel actions");
assert.ok(queue.includes('job.status==="PUBLISHED"') || queue.includes('job.status === "PUBLISHED"'), "Published status should remain visible");
assert.ok(progress.includes("onNavigate") && progress.includes("skipDetails"), "Progress must allow back-navigation and skip story details");
assert.ok(skeleton.includes('view === "queue"') && skeleton.includes('view === "editor"'), "Skeletons for queue/editor are required");
assert.ok(edit.includes('<PublishingPageSkeleton view="editor" />'), "Edit screen should not use a full-page spinner");
assert.ok(!tags.includes("window.fetch ="), "Publishing tag wrapper must not override global fetch");
assert.ok(wizard.includes("taggedUsersByMedia[item.storageKey]"), "Per-media tags must be serialized directly");
assert.ok(workflow.includes("PublishingWithTags"), "Existing published route must still resolve");
assert.ok(existsSync("app/dashboard/publishing/loading.tsx"), "Create route skeleton missing");
assert.ok(src("app/dashboard/publishing/[id]/loading.tsx").includes('view="editor"'), "Editor route skeleton missing");
